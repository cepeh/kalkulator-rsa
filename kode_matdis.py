# 1. FUNGSI MATEMATIKA & GENERATOR PRIMA
# ==========================================
def is_prime(n: int, k: int = 12) -> bool:
    """Uji bilangan prima (Miller-Rabin) cepat untuk angka hingga 24+ digit."""
    if n < 2:
        return False
    if n in (2, 3):
        return True
    if n % 2 == 0:
        return False

    r, d = 0, n - 1
    while d % 2 == 0:
        r += 1
        d //= 2

    for _ in range(k):
        a = random.randrange(2, n - 1)
        x = pow(a, d, n)
        if x in (1, n - 1):
            continue
        for _ in range(r - 1):
            x = pow(x, 2, n)
            if x == n - 1:
                break
        else:
            return False
    return True

def generate_random_prime(digits: int, exclude: int = None) -> int:
    """Menghasilkan bilangan prima acak dengan jumlah digit tertentu (1 - 24 digit)."""
    if digits == 1:
        prima_1_digit = [p for p in [2, 3, 5, 7] if p != exclude]
        return random.choice(prima_1_digit)

    batas_bawah = 10**(digits - 1)
    batas_atas = (10**digits) - 1

    while True:
        kandidat = random.randint(batas_bawah, batas_atas)
        if kandidat % 2 == 0:
            kandidat += 1
            if kandidat > batas_atas:
                kandidat -= 2

        if kandidat != exclude and is_prime(kandidat):
            return kandidat

def generate_random_e(m: int) -> int:
    """Memilih nilai e secara acak di mana 1 < e < m dan PBB(e, m) = 1."""
    if m <= 10000:
        kandidat = [e for e in range(3, m, 2) if math.gcd(e, m) == 1]
        if not kandidat:
            kandidat = [e for e in range(2, m) if math.gcd(e, m) == 1]
        return random.choice(kandidat)

    while True:
        e = random.randrange(3, m, 2)
        if math.gcd(e, m) == 1:
            return e

